_restore = {}


def restore_all(*_):
    for path, text in _restore.items():
        with open(path, "w") as handle:
            handle.write(text)
    _restore.clear()


def on_signal(signum, _frame):
    restore_all()
    print(f"\n  {ERR}interrompu — le code source est restaure{Z}")
    sys.exit(130)


KNOWN_FLAGS = ("--list", "--check-anchors")
KNOWN_OPTIONS = ("--only", "--match")


def refuse(message):
    print(f"  {ERR}invocation refusee{Z} {DIM}{message}{Z}")
    print(f"  {DIM}Aucun mutant n'a ete execute.{Z}")
    return None


def selected(argv):
    """Rend la liste des mutants a executer, ou None si l invocation est refusee.

    Un argument inconnu ne doit PAS se lire comme une passe complete, et un
    filtre qui ne selectionne rien ne doit pas se lire comme une passe reussie.
    """
    i = 0
    only = match = None
    while i < len(argv):
        arg = argv[i]
        if arg in KNOWN_FLAGS:
            i += 1
        elif arg in KNOWN_OPTIONS:
            if i + 1 >= len(argv) or argv[i + 1].startswith("--"):
                return refuse(f"{arg} attend une valeur")
            if arg == "--only":
                only = argv[i + 1]
            else:
                match = argv[i + 1]
            i += 2
        else:
            return refuse(f"argument inconnu : {arg}")

    mutants = list(MUTANTS)
    if only is not None:
        # Three families carry a two-word prefix -- "ts drift:", "ts reconcile:",
        # "ts gestures:" -- so a plain startswith(want + ":") hid 29 mutants from
        # --only ts while a full pass still ran them. Match the first word.
        mutants = [m for m in mutants
                   if m[0].split(":", 1)[0].split(" ", 1)[0] == only]
        if not mutants:
            return refuse(f"--only {only} ne selectionne aucun mutant")
    if match is not None:
        mutants = [m for m in mutants if match in m[0]]
        if not mutants:
            return refuse(f"--match {match!r} ne selectionne aucun mutant")
    return mutants


def check_anchors(mutants):
    """Verifie les ancres SANS muter et SANS compiler.

    Une ancre absente ou ambigue rend la mutation inapplicable, et la sonde
    s'arrete alors au milieu d'une passe qui dure des dizaines de minutes. Ce
    controle repond en quelques secondes. Il est ne d'une panne reelle : le
    2026-08-29, 22 mutants sur 230 etaient inapplicables -- 16 ancres perimees
    par le passage du codec a des fonctions libres, 6 rendues ambigues par la
    duplication des defauts entre la version 2 et la version 3.
    """
    absent = []
    ambiguous = []
    unreadable = []
    unknown_suite = []
    for label, rel, old, _new, suite in mutants:
        if suite not in SUITES:
            unknown_suite.append((label, suite))
        path = os.path.join(ROOT, rel)
        try:
            with open(path) as handle:
                body = handle.read()
        except OSError as error:
            unreadable.append((label, rel, error))
            continue
        found = body.count(old)
        if found == 0:
            absent.append((label, rel))
        elif found > 1:
            ambiguous.append((label, rel, found))

    print(f"{B}=================== ANCRES DE MUTATION ==================={Z}")
    print(f"  mutants examines   {len(mutants)}")
    for label, rel, error in unreadable:
        print(f"  {ERR}fichier illisible{Z}  {label}   {DIM}{rel} : {error}{Z}")
    for label, rel in absent:
        print(f"  {ERR}ancre ABSENTE{Z}      {label}   {DIM}{rel}{Z}")
    for label, rel, found in ambiguous:
        print(f"  {ERR}ancre AMBIGUE{Z}      {label}   {DIM}{rel} : {found} cibles{Z}")
    for label, suite in unknown_suite:
        print(f"  {ERR}SUITE INCONNUE{Z}     {label}   {DIM}tag \"{suite}\" absent de SUITES{Z}")
    broken = len(absent) + len(ambiguous) + len(unreadable) + len(unknown_suite)
    if broken:
        print(f"  {ERR}{broken} ancre(s) inapplicable(s){Z} — la passe complete "
              f"s'arreterait dessus.")
        print(f"  {DIM}Recibler sans deplacer le critere de detection : une ancre "
              f"elargie doit voir sa cible elargie d'autant.{Z}")
        return 2
    print(f"  {OK}toutes presentes exactement une fois{Z}")
    return 0


def main():
    argv = sys.argv[1:]
    mutants = selected(argv)
    if mutants is None:
        return 3

    if "--list" in argv:
        for label, rel, _, _, suite in mutants:
            print(f"  {label}   {DIM}{rel} [{suite}]{Z}")
        print(f"\n  {len(mutants)} mutants")
        return 0

    if "--check-anchors" in argv:
        return check_anchors(mutants)

    for name in ("cpp", "ts"):
        if any(m[4].startswith(name) for m in mutants):
            command, cwd = SUITES["cpp" if name == "cpp" else "ts"]
            if not os.path.exists(os.path.join(cwd, command[0])) and command[0] != "npx":
                print(f"  {ERR}suite introuvable : {command[0]}{Z}")
                return 127

    signal.signal(signal.SIGINT, on_signal)
    signal.signal(signal.SIGTERM, on_signal)

    print(f"{B}=================== MUTATIONS DU DOMAINE ==================={Z}")
    killed = survived = 0
    for label, rel, old, new, suite in mutants:
        path = os.path.join(ROOT, rel)
        original = open(path).read()
        seen = original.count(old)
        if seen == 0:
            print(f"  {ERR}❌ MOTIF ABSENT{Z}  {label}")
            print(f"     {DIM}{rel} a change : ce mutant ne s'applique plus, il ne prouve rien.{Z}")
            print(f"     {DIM}Corriger la liste, jamais l'ignorer.{Z}")
            return 2
        if seen > 1:
            print(f"  {ERR}❌ MOTIF AMBIGU{Z}  {label}")
            print(f"     {DIM}{rel} contient ce motif {seen} fois ; seule la premiere serait mutee.{Z}")
            print(f"     {DIM}Elargir le motif jusqu'a ce qu'il ne designe qu'une cible.{Z}")
            return 2

        command, cwd = SUITES[suite]
        _restore[path] = original
        try:
            with open(path, "w") as handle:
                handle.write(original.replace(old, new, 1))
            try:
                done = subprocess.run(command, cwd=cwd, capture_output=True,
                                      text=True, timeout=TIMEOUT)
                code = done.returncode
            except subprocess.TimeoutExpired:
                code = "timeout"
        finally:
            restore_all()

        if code == "timeout":
            print(f"  {OK}✅ tue{Z} {DIM}(boucle infinie, delai {TIMEOUT} s){Z}  {label}")
            killed += 1
        elif code != 0:
            print(f"  {OK}✅ tue{Z}      {label}")
            killed += 1
        else:
            print(f"  {ERR}❌ SURVIVANT{Z} {label}")
            survived += 1

    total = killed + survived
    print(f"{B}============================================================{Z}")
    if survived:
        print(f"  {ERR}{killed}/{total} tues — {survived} survivant(s).{Z}")
        print(f"  {DIM}Un survivant designe une assertion manquante, ou une assertion qui se{Z}")
        print(f"  {DIM}compare a la constante qu'elle teste.{Z}")
        return 1
    print(f"  {OK}{killed}/{total} tues.{Z}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
